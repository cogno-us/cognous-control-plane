# =========================================================================================================== legacy binary on a new record
def legacy_reader(store, res, profile, **kw):
    """The UNCHANGED comparison code: the plain `BoundedAuthorizationWorkflow` (no governed lifecycle, no `_resolve` override) on the same store, profile and scalars."""
    return BoundedAuthorizationWorkflow(manifest=T.base.manifest(), resolver=res, destination=LocalRefundDestination(Path(store) / "destination.json"),
                                        records=T.base.BoundedRecordStore(Path(store) / "run.json", "run-1"), allow_test_time=True, runtime_authority_profile=profile,
                                        observation_policy=ObservationPolicy(max_age_seconds=300, clock_tolerance_seconds=5), **kw)


def test_b01_a_legacy_reader_fails_closed_on_a_new_record(tmp_path):
    """Typed models, real code: the legacy comparison is `current != persisted.binding` over the whole `runtime_authority` dict, so a one-key-larger persisted dict refuses."""
    p, res, cfg, srcs, flow, d = S.authorized(tmp_path)
    persisted = flow.records.decision(d.decision_id)
    legacy_current = persisted.binding.model_copy(update={"runtime_authority": {k: v for k, v in persisted.binding.runtime_authority.items() if k != ecb.KEY}})
    assert legacy_current != persisted.binding  # what a legacy `_resolve` would rebuild vs what is persisted
    reader = legacy_reader(tmp_path, res, flow.runtime_authority_profile)
    n = len(reader.records.load().refusals)
    with pytest.raises(PermissionError, match="authorization-critical inputs changed before effect"):
        reader.execute(p, persisted, adapter_id=p.adapter_id, now=NOW)
    ref = reader.records.load().refusals[n]
    assert ref.reasons == [CODE] and reader.destination.snapshot()["effects"] == {}


def test_b02_the_legacy_reader_accepts_a_legacy_record_so_the_failure_is_the_new_member_only(tmp_path):
    store = fixture_store(tmp_path, "composed")
