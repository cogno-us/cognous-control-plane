# ============================================================================================================================ separate process
def run_worker(mode, store, decision_id, **cfg):
    env = dict(os.environ, PYTHONPATH=os.pathsep.join([str(ROOT / "src"), str(ROOT)]))
    proc = subprocess.run([sys.executable, "-m", "tests.d06_worker", mode, str(store), decision_id, json.dumps(cfg)], cwd=ROOT, env=env, capture_output=True, text=True, timeout=300)
    assert proc.returncode == 0, proc.stderr[-2000:]
    return json.loads(proc.stdout.strip().splitlines()[-1])


def test_c01_recovery_in_a_separate_process_accepts_the_same_configuration(tmp_path):
    p, res, cfg, srcs, flow, d = S.authorized(tmp_path)
    out = run_worker("execute", tmp_path, d.decision_id)
    assert out["outcome"] == "executed" and out["status"] == ecb.BOUND, out
    # the effect really landed in the persisted destination, and the parent sees it
    assert len(flow.destination.snapshot()["effects"]) == 1


@pytest.mark.parametrize("drift", [dict(status=59), dict(identity=59), dict(tolerance=6), dict(obs=[299, 5]), dict(obs=[300, 6]), dict(obs="none"), dict(f4=True)])
def test_c02_recovery_in_a_separate_process_refuses_a_changed_configuration(tmp_path, drift):
    p, res, cfg, srcs, flow, d = S.authorized(tmp_path)
    out = run_worker("execute", tmp_path, d.decision_id, **drift)
    assert out["outcome"] == "refused" and out["status"] == ecb.MISMATCH and out["reasons"] == [CODE], out
    assert flow.destination.snapshot()["effects"] == {}
    refusals = flow.records.load().refusals
    assert refusals and refusals[-1].decision_id == d.decision_id and refusals[-1].reasons == [CODE]  # durable EffectTimeRefusal written by the OTHER process


def test_c03_a_legacy_store_in_a_separate_process_follows_the_cutoff(tmp_path):
    for cutoff, expected in ((None, "refused"), (1, "executed")):
        work = tmp_path / f"w{cutoff}"
        work.mkdir()
        store = fixture_store(work, "composed")
        cfg = dict(f4=True, **({} if cutoff is None else {"cutoff": cutoff}))
        out = run_worker("execute", store, META["composed"]["decision_id"], **cfg)
        assert out["outcome"] == expected, out
        assert out["status"] == (ecb.UNBOUND_AFTER_CUTOFF if cutoff is None else ecb.LEGACY)


def test_c04_pin_export_replay_in_a_separate_process(tmp_path):
    p, res, profile, binding, store, flow, d = pin_decision(tmp_path)
    same = run_worker("pin", store, d.decision_id)
    assert same["outcome"] == "executed" and same["state"] == "active" and same["status"] == ecb.BOUND, same
    for drift in (dict(identity=59), dict(obs=[299, 5]), dict(tolerance=6)):
        changed = run_worker("pin", store, d.decision_id, **drift)
        assert changed["outcome"] == "refused" and changed["state"] != "active" and changed["status"] == ecb.MISMATCH, (drift, changed)


def test_c05_a_corrupted_member_is_refused_by_a_separate_process_too(tmp_path):
    p, res, cfg, srcs, flow, d = S.authorized(tmp_path)
