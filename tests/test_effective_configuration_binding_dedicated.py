def make(kind, store, res, cfg, *, f=None, a=None, u=None, **extra):
    """One dedicated workflow over the store under `store`. `f`, `a`, `u` override the selection source of the F4, class-age and class-unreadable family respectively."""
    kw = T.kwargs(store, res)
    if "obs" in extra:
        kw["observation_policy"] = extra.pop("obs")
    verifier = S.ev.Ed25519Verifier()
    if kind == "dedicated_f4":
        return f4gov.GovernedAgeWorkflow(scope=T.SCOPE_F, selection_source=f or T.fsrc(), verifier=verifier, construction_time=S.REG_NOW, **extra, **kw)
    if kind == "dedicated_age":
        return agegov.GovernedClassAgeWorkflow(scope=T.SCOPE_A, selection_source=a or T.asrc(), verifier=verifier, runtime_authority_profile=cfg, construction_time=S.REG_NOW,
                                               **extra, **kw)
    joint = dict(class_age_scope=T.SCOPE_A, class_age_selection_source=a or T.asrc()) if kind == "dedicated_unr_age" else {}
    return ugov.GovernedClassUnreadableWorkflow(scope=T.base.SCOPE, selection_source=u or T.usrc(), verifier=verifier, runtime_authority_profile=cfg, construction_time=S.REG_NOW,
                                                **joint, **extra, **kw)


def setup(kind, tmp_path, **overrides):
    """(proposal, resolver, host profile, store dir, workflow). Approvals are bound to the FINAL profile when the workflow carries one."""
    store = tmp_path / "store"
    store.mkdir(exist_ok=True)
    if kind == "dedicated_f4":
        p = T.base.tenant_proposal()
        res, cfg = T.base.tenant_resolver_for(p), None
    else:
        p, res, cfg = T.prepared(tmp_path / "work")
    flow = make(kind, store, res, cfg, **overrides)
    rebind(res, flow)
    return p, res, cfg, store, flow


def rebind(res, flow):
    if flow.runtime_authority_profile is not None:
        T.bind_approval(res, flow.runtime_authority_profile)


def authorized(kind, tmp_path, **overrides):
    p, res, cfg, store, flow = setup(kind, tmp_path, **overrides)
    d = flow.decide(p, now=NOW)
    assert d.result == "authorized", d.reasons
    return p, res, cfg, store, flow, d


def changed_family(kind):
    """A different, valid selection for the family(ies) this workflow governs (the effective value differs)."""
