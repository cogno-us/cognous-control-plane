def test_d20_an_unreadable_store_while_counting_the_decisions_refuses_a_positive_cutoff(tmp_path, monkeypatch):
    """The cutoff is judged against the decisions in the store at construction; if they cannot be counted the construction is refused (fail closed). A cutoff of 0 reads nothing."""
    from agent_control_plane.bounded import BoundedRecordStore
    p, res, cfg, store, flow, d = authorized("dedicated_f4", tmp_path)
    real, calls = BoundedRecordStore.load, []

    def counting(self):
        calls.append(1)
        return real(self)
    monkeypatch.setattr(BoundedRecordStore, "load", counting)
    make("dedicated_f4", store, res, cfg)  # cutoff 0
    n = len(calls)
    calls.clear()

    def failing(self):
        calls.append(1)
        if len(calls) > n:  # the one extra read a positive cutoff adds, as the last step of the construction
            raise OSError("store unreadable")
        return real(self)
    monkeypatch.setattr(BoundedRecordStore, "load", failing)
    with pytest.raises(RegistrySelectionRefused) as e:
        make("dedicated_f4", store, res, cfg, legacy_cutoff=1)
    assert e.value.refusal.code == "legacy_cutoff_invalid" and e.value.boundary == "construction"
